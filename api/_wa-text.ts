// Тексты WhatsApp. Антиспам WhatsApp реагирует на одинаковые сообщения многим людям,
// поэтому фразы собираются из случайных кусочков. Казахский — простой разговорный.

type Lang = 'ru' | 'kk'
const pick = <T>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)]

const GREET: Record<Lang, string[]> = {
  ru: ['Здравствуйте', 'Добрый день', 'Приветствую', 'Здравствуйте'],
  kk: ['Сәлеметсіз бе', 'Қайырлы күн', 'Сәлем', 'Амансыз ба']
}
function greet(name: string, lang: Lang): string {
  const g = pick(GREET[lang])
  return `${name && Math.random() < 0.85 ? `${g}, ${name}` : g}!${pick(['', '', ' 👋', ' 😊'])}`
}

const PAID: Record<Lang, { intro: string[]; lead: string[]; close: string[] }> = {
  ru: {
    intro: ['Оплата прошла — ваш нейропрофиль открыт.', 'Спасибо за оплату! Результат теста готов.', 'Всё готово: результат теста Бравермана открыт.'],
    lead: ['Ваша личная ссылка на результат:', 'Открыть результат можно здесь:', 'Ссылка на результат:'],
    close: ['Сохраните это сообщение — ссылка постоянная.', 'Ссылка работает всегда, можно вернуться в любое время.', 'Сохраните ссылку: по ней результат и видео-разбор откроются в любой момент.']
  },
  kk: {
    intro: ['Төлем өтті — нейропрофиліңіз ашық.', 'Төлеміңіз үшін рахмет! Тест нәтижесі дайын.', 'Бәрі дайын: Браверман тестінің нәтижесі ашылды.'],
    lead: ['Нәтижеңіздің жеке сілтемесі:', 'Нәтижені осы жерден ашасыз:', 'Нәтиже сілтемесі:'],
    close: ['Осы хабарламаны сақтап қойыңыз — сілтеме тұрақты.', 'Сілтеме әрқашан жұмыс істейді, кез келген уақытта қайта кіре аласыз.', 'Сілтемені сақтаңыз: нәтиже мен видео-талдау кез келген уақытта ашылады.']
  }
}

export function resultLinkMessage(name: string, link: string, lang: Lang = 'ru'): string {
  const t = PAID[lang] || PAID.ru
  return `${greet(name, lang)}${pick([' 🎉', ' ✅', ''])}\n${pick(t.intro)}${pick(['\n', ' '])}${pick(t.lead)}\n${link}\n\n${pick(t.close)}`
}

const OTP: Record<Lang, { lead: string[]; close: string[] }> = {
  ru: { lead: ['Код для входа к результату:', 'Ваш код:', 'Тест Бравермана — код подтверждения:'], close: ['Код действует 5 минут.', 'Введите в течение 5 минут.', 'Никому не сообщайте код. Действует 5 минут.'] },
  kk: { lead: ['Нәтижеге кіру коды:', 'Сіздің кодыңыз:', 'Браверман тесті — растау коды:'], close: ['Код 5 минут жарамды.', '5 минут ішінде енгізіңіз.', 'Кодты ешкімге айтпаңыз. 5 минут жарамды.'] }
}

export function otpMessage(code: string, lang: Lang = 'ru'): string {
  const t = OTP[lang] || OTP.ru
  return `${pick(t.lead)} ${code}\n${pick(t.close)}${Math.random() < 0.3 ? ' 🔐' : ''}`
}
