const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1).toLowerCase()

export function firstName(raw: string | null | undefined): string {
  const words = String(raw || '').split(/\s+/).map(w => w.replace(STRIP, '')).filter(w => w.length > 1)
  if (!words.length) return ''
  if (words.length === 1) return cap(words[0])
  const rest = words.filter(w => !PATRONYMIC.test(w))
  const byDict = rest.find(w => NAMES.has(w.toLowerCase()))
  if (byDict) return cap(byDict)
  const notSurname = rest.filter(w => !SURNAME.test(w))
  if (notSurname.length === 1) return cap(notSurname[0])
  const pool = notSurname.length ? notSurname : rest.length ? rest : words
  return cap(pool[Math.min(1, pool.length - 1)]) // Фамилия Имя [Отчество] — имя второе
}
